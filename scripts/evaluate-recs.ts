/**
 * Offline evaluation of the recommender on the database's bookmarks and ratings.
 *
 *   npm run recs:eval                 print the results table
 *   npm run recs:eval -- --write      also save docs/recommendation-evaluation.md
 *   npm run recs:eval -- --check      exit 1 if the production ranking stops beating
 *                                     popularity and random, or falls more than 5%
 *                                     below the best single strategy (CI)
 *
 * In GitHub Actions the table is also added to the job summary.
 */
import "dotenv/config";
import fs from "node:fs";
import path from "node:path";
import { titleToMediaItem } from "@/lib/catalog";
import { db } from "@/lib/db";
import { evaluate, toMarkdownTable, type Interaction } from "@/lib/recs/evaluate";

const PRODUCTION = "hybrid + diversity (production)";

async function main() {
  const args = new Set(process.argv.slice(2));
  const [bookmarks, ratings, titles] = await Promise.all([
    db.bookmark.findMany({ select: { userId: true, titleId: true, createdAt: true } }),
    db.rating.findMany({ select: { userId: true, titleId: true, score: true, updatedAt: true } }),
    db.title.findMany(),
  ]);

  const interactions: Interaction[] = [
    ...bookmarks.map((b) => ({ userId: b.userId, titleId: b.titleId, kind: "bookmark" as const, at: b.createdAt })),
    ...ratings.map((r) => ({ userId: r.userId, titleId: r.titleId, kind: "rating" as const, score: r.score, at: r.updatedAt })),
  ];
  const catalog = titles.map((t) => ({ titleId: t.id, item: titleToMediaItem(t) }));

  const started = performance.now();
  const report = evaluate(interactions, catalog, { k: 10 });
  const ms = Math.round(performance.now() - started);

  const table = toMarkdownTable(report);
  const summary =
    `Hold-out evaluation: ${report.usersEvaluated} users, ${report.catalogSize} titles, ` +
    `${report.interactions} bookmarks and ratings, 20% of each user's liked titles hidden, ` +
    `averaged over ${report.seeds.length} random splits (${ms} ms).`;
  console.log(`${summary}\n\n${table}\n`);

  const get = (name: string) => report.results.find((r) => r.strategy === name)!;
  const prod = get(PRODUCTION);
  const pop = get("popularity");
  const rand = get("random");
  const lift = pop.recall > 0 ? `${(prod.recall / pop.recall).toFixed(1)}x` : "n/a (popularity found nothing)";
  console.log(`Production ranking recall@10 vs popularity: ${lift}`);

  if (process.env.GITHUB_STEP_SUMMARY) {
    fs.appendFileSync(
      process.env.GITHUB_STEP_SUMMARY,
      `## Recommendation quality\n\n${summary}\n\n${table}\n\nProduction vs popularity (recall@10): **${lift}**\n`,
    );
  }

  if (args.has("--write")) {
    const file = path.join("docs", "recommendation-evaluation.md");
    fs.mkdirSync("docs", { recursive: true });
    fs.writeFileSync(
      file,
      `# Recommendation evaluation\n\nGenerated by \`npm run recs:eval -- --write\` on ${new Date().toISOString().slice(0, 10)}.\n\n` +
        `${summary}\n\n${table}\n\nProduction vs popularity (recall@10): **${lift}**\n`,
    );
    console.log(`Wrote ${file}`);
  }

  if (args.has("--check")) {
    const failures: string[] = [];
    if (report.usersEvaluated < 10) failures.push(`only ${report.usersEvaluated} users had enough data (need 10)`);
    if (!(prod.recall > pop.recall)) failures.push("production ranking no longer beats popularity on recall@10");
    if (!(prod.recall > rand.recall * 1.5)) failures.push("production ranking is barely better than random");
    const singles = ["popularity", "content-based", "collaborative"].map(get);
    const bestSingle = singles.reduce((a, b) => (b.recall > a.recall ? b : a));
    if (!(prod.recall >= bestSingle.recall * 0.95)) {
      failures.push(`production ranking fell more than 5% below ${bestSingle.strategy} alone, so blending no longer helps`);
    }
    if (failures.length) {
      console.error(`Quality check failed:\n- ${failures.join("\n- ")}`);
      process.exitCode = 1;
    } else {
      console.log("Quality check passed.");
    }
  }
}

main()
  .catch((e) => {
    console.error(e);
    process.exitCode = 1;
  })
  .finally(() => db.$disconnect());
